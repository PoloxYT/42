#include "ft_printf.h"

void	ft_putstr(char *s, int sens)
{
	int	i;

	i = 0;
	if (sens == 1)
	{
		while (s[i] != 0)
		{
			write(1, &s[i], 1);
			i += 1;
		}
	}
	else if (sens == 2)
	{
		while (s[i] != 0)
			i += 1;
		while (i >= 0)
		{
			write(1, &s[i], 1);
			i -= 1;
		}
	}
}
